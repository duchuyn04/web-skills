"""Write kit/icons.js from data/icons.json (Lucide paths, ISC licence) plus the app icons listed below.

    python scripts/make_icons.py

kit/app.js turns window.UI_ICONS into one hidden <svg> sprite at load, so a page draws an icon with
<svg class="ico" aria-hidden="true"><use href="#i-check"/></svg>. An inline sprite works from file:// too,
where Chrome refuses <use> on an external .svg file.
"""
import json
from pathlib import Path

SKILL = Path(__file__).resolve().parent.parent

# Lucide icons the shop set does not carry; same 24x24 grid and stroke.
EXTRA = {
    "arrow-left": '<path d="m12 19-7-7 7-7"/><path d="M19 12H5"/>',
    "arrow-up-down": '<path d="m21 16-4 4-4-4"/><path d="M17 20V4"/><path d="m3 8 4-4 4 4"/><path d="M7 4v16"/>',
    "folder": '<path d="M20 20a2 2 0 0 0 2-2V8a2 2 0 0 0-2-2h-7.9a2 2 0 0 1-1.69-.9L9.6 3.9A2 2 0 0 0 7.93 3H4a2 2 0 0 0-2 2v13a2 2 0 0 0 2 2Z"/>',
    "globe": '<circle cx="12" cy="12" r="10"/><path d="M12 2a14.5 14.5 0 0 0 0 20 14.5 14.5 0 0 0 0-20"/><path d="M2 12h20"/>',
    "inbox": '<polyline points="22 12 16 12 14 15 10 15 8 12 2 12"/><path d="M5.45 5.11 2 12v6a2 2 0 0 0 2 2h16a2 2 0 0 0 2-2v-6l-3.45-6.89A2 2 0 0 0 16.76 4H7.24a2 2 0 0 0-1.79 1.11z"/>',
    "key": '<path d="m15.5 7.5 2.3 2.3a1 1 0 0 0 1.4 0l2.1-2.1a1 1 0 0 0 0-1.4L19 4"/><path d="m21 2-9.6 9.6"/><circle cx="7.5" cy="15.5" r="5.5"/>',
    "loader": '<path d="M21 12a9 9 0 1 1-6.219-8.56"/>',
    "panel-left": '<rect width="18" height="18" x="3" y="3" rx="2"/><path d="M9 3v18"/>',
}


def main():
    icons = json.loads((SKILL / "data" / "icons.json").read_text(encoding="utf-8"))
    icons.update(EXTRA)
    body = json.dumps(dict(sorted(icons.items())), ensure_ascii=False, separators=(",", ":"))
    out = SKILL / "kit" / "icons.js"
    out.write_text("/* Generated by scripts/make_icons.py. Lucide icons (https://lucide.dev), ISC licence. Do not edit. */\n"
                   "window.UI_ICONS=" + body + ";\n", encoding="utf-8")
    print("wrote %s: %d icons" % (out, len(icons)))


if __name__ == "__main__":
    main()

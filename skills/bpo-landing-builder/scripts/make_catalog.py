def write_animation_map(lib):
    where = {}
    for key, v in lib["variants"].items():
        for a in v.get("animations", []):
            where.setdefault(a.split(" ")[0], []).append(key)
    out = ["# Animation map", "",
           "Generated by `scripts/make_catalog.py`. Every animation below is already coded inside the section templates. You never write animation code: choose the section that carries the effect.", "",
           "All motion follows the performance rules gathered in the research: only transform and opacity animate, easing is `cubic-bezier(0.16, 1, 0.3, 1)` (GSAP `expo.out`) unless noted, and `prefers-reduced-motion` turns movement off. Tweens run on GSAP and 3D scenes on Three.js WebGL; see `motion-libraries.md`.", "",
           "| Animation id | Built into | Timing |", "|:---|:---|:---|"]
    for a, t in TIMING.items():
        out.append("| `%s` | %s | %s |" % (a, ", ".join("`%s`" % v for v in where.get(a, [])) or "none", t))
    out += ["", "## Design options (page-wide)", "",
            "These are not tied to one section. The preset sets them and `theme` in page.json can override them.", "",
            "| Option | Values | Effect |", "|:---|:---|:---|",
            "| `edges` | none, angle, curve | Bottom edge of the hero and of dark sections is cut at an angle or curved; the next section slides under it. |",
            "| `image_mask` | rounded, angle, arch | Photo frames (feature rows, split heroes, tabs, boxed banners) get a cut corner or an arched top. |",
            "| `highlight` | color, gradient, underline | How `*accent*` words in headings look. |",
            "| `media_reveal` | fade, clip | `clip` wipes photos up from the bottom (0.9s) as they enter. |",
            "| `motion_style` | rise, slide, fade, mask | How elements arrive on scroll (see `reveal` above and `motion-research.md`). Leave it out: build.py picks one from the brand name (rise 35%, slide 25%, fade 25%, mask 15% of brands), so pages for different clients move differently. Set it only when the client asks for calmer or livelier motion. |", ""]
    out += ["", "`magnetic-cta-button` is off by default. Turn it on with `\"features\": {\"magnetic_cta\": true}` in page.json.", ""]
    (SKILL / "references" / "animation-map.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote references/animation-map.md")



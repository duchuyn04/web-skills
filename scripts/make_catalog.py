#!/usr/bin/env python3
"""Regenerate references/section-catalog.md from every sections/*/schema.json, and optionally
refresh previews/<variant>.jpg from built example pages.

Usage:
    python make_catalog.py                          rewrite the catalog only
    python make_catalog.py --previews dist1 dist2   also copy preview images; each dist must have
                                                    build-report.json and qa/sections-1440 from
                                                    qa_screenshot.py --sections
Run it after adding or changing a section so the docs match the code.
"""
import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import build  # noqa: E402

SKILL = HERE.parent
PREVIEWS = SKILL / "previews"


def field_line(name, fs, indent=0):
    t = fs.get("type", "text")
    req = "" if fs.get("required", True) and "default" not in fs else " (optional)"
    if "default" in fs and fs["default"] not in ([], None):
        req = " (optional, default %s)" % json.dumps(fs["default"])
    pad = "  " * indent
    if t in ("text", "markup", "email", "phone"):
        desc = "%s %d-%d chars" % ("text with *accent*" if t == "markup" else t, fs.get("min", 1), fs.get("max", 400))
    elif t == "list":
        n = " or ".join(str(c) for c in fs["counts"]) if fs.get("counts") else "%d-%d" % (fs.get("min", 0), fs.get("max", 99))
        desc = "list of %s" % n
    elif t == "enum":
        desc = "one of %s" % ", ".join(fs["values"])
    elif t == "stat":
        desc = "number (or \"[KPI]\" placeholder)"
    elif t == "number":
        desc = "number %s-%s" % (fs.get("min", ""), fs.get("max", ""))
    else:
        desc = {"icon": "icon name", "flag": "country code", "image": "image key or path", "city": "city key",
                "href": "link", "bool": "true/false", "object": "object", "color": "hex color", "audio": "audio file path"}.get(t, t)
    lines = ["%s- `%s`: %s%s" % (pad, name, desc, req)]
    sub = None
    if t == "object":
        sub = fs["fields"]
    elif t == "list" and fs["item"].get("type") == "object":
        sub = fs["item"]["fields"]
        lines[0] += ", each item:"
    elif t == "list":
        it = fs["item"]
        lines[0] += " (each %s %d-%d chars)" % (it.get("type", "text"), it.get("min", 1), it.get("max", 400))
    if sub:
        for k, v in sub.items():
            lines += field_line(k, v, indent + 1)
    return lines


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--previews", nargs="*", default=[])
    args = ap.parse_args()
    lib = build.load_library()

    if args.previews:
        from PIL import Image
        PREVIEWS.mkdir(exist_ok=True)
        for dist in args.previews:
            dist = Path(dist)
            rep = json.loads((dist / "build-report.json").read_text(encoding="utf-8"))
            shown = [s for s in rep["sections"] if s.get("group") != "floating"]
            shots = sorted((dist / "qa" / "sections-1440").glob("*.jpg"))
            for sec, shot in zip(shown, shots):
                target = PREVIEWS / (sec["type"] + ".jpg")
                if target.exists():
                    continue
                im = Image.open(shot).convert("RGB")
                im.thumbnail((720, 900))
                im.save(target, quality=72)
                print("preview", target.name)

    uses = {}
    for key, arch in lib["archetypes"].items():
        for slot in arch["slots"]:
            for v in slot["variants"]:
                uses.setdefault(v, []).append("%s/%s%s" % (key, slot["slot"], "" if slot.get("required") else "?"))

    out = ["# Section catalog", "",
           "Generated by `scripts/make_catalog.py` from each `templates/sections/*/schema.json`. Do not edit by hand.", "",
           "Every section in page.json is `{\"type\": \"<variant>\", \"data\": {...}}`. Optional keys next to type: `id` (anchor, lowercase) and `tone` (light, muted or dark). Leave both out unless you have a reason.", "",
           "Accent markup: in fields marked \"text with *accent*\", wrap 1-4 words in asterisks to color them, for example `\"Support teams that *protect your CSAT*\"`. Use it once per title. Paragraph fields marked the same way also accept `**bold**` for key terms.", ""]
    out += ["## Page-level fields", "", "These sit at the top of page.json, next to `sections`.", ""]
    for name, fs in build.PAGE_SPEC["fields"].items():
        if name != "sections":
            out += field_line(name, fs)
    out.append("")
    for key, v in lib["variants"].items():
        out += ["## %s" % key, "", v["summary"], ""]
        out.append("- Group: `%s`. Default anchor: `#%s`. Tone: %s.%s" % (v.get("group"), v.get("anchor"), v.get("tone", "auto"), " Expressive tier: only on pages with `\"motion\": \"expressive\"` (a brief that asks for a 3D or animation-led page)." if v.get("tier") == "expressive" else ""))
        if v.get("animations"):
            out.append("- Built-in motion: %s." % ", ".join(v["animations"]))
        out.append("- Allowed in: %s." % (", ".join(uses.get(key, [])) or "custom order only"))
        if (PREVIEWS / (key + ".jpg")).exists():
            out.append("- Preview: `previews/%s.jpg`" % key)
        out += ["", "Fields:", ""]
        for name, fs in v["fields"].items():
            out += field_line(name, fs)
        out.append("")
    (SKILL / "references" / "section-catalog.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote references/section-catalog.md (%d variants)" % len(lib["variants"]))
    write_anatomy(lib)
    write_animation_map(lib)


def write_anatomy(lib):
    out = ["# Page anatomy", "",
           "Generated by `scripts/make_catalog.py` from `templates/archetypes.json`. Do not edit by hand.", "",
           "## Pick one archetype", "",
           "Match the client's main offer, not its size. If two fit, pick the one whose first required section after the hero matches what the client sells hardest (cost savings, call quality, AI data, or breadth of services).", "",
           "| Archetype | Use for | Dataset categories | Reference sites | Default preset |",
           "|:---|:---|:---|:---|:---|"]
    for key, a in lib["archetypes"].items():
        out.append("| `%s` | %s | %s | %s | `%s` |" % (key, a["use_for"], ", ".join(a["categories"]), ", ".join(a["references"]), a["default_preset"]))
    out += ["", "## Slot order", "",
            "Sections in page.json must appear in this order. Each slot is used once. Floating widgets (floating-chat, exit-intent-modal) go last.", "",
            "- yes: must be present.",
            "- recommended: include it when the client gave you the real content (logos, testimonials or case results, salary rates, call recordings). Leave it out otherwise; never fill it with invented content.",
            "- no: optional; include it when it helps the pitch.", ""]
    for key, a in lib["archetypes"].items():
        out += ["### %s" % key, "", "| # | Slot | Required | Allowed types |", "|:---|:---|:---|:---|"]
        for i, s in enumerate(a["slots"], 1):
            out.append("| %d | %s | %s | %s |" % (i, s["slot"], "yes" if s.get("required") else ("recommended" if s.get("recommended") else "no"), ", ".join("`%s`" % v for v in s["variants"])))
        out.append("")
    (SKILL / "references" / "page-anatomy.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote references/page-anatomy.md")


